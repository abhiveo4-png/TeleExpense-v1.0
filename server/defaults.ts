export function getIstDateTime(inputDate?: string | number | Date): { date: string; time: string; month: string } {
  const base = inputDate ? new Date(inputDate) : new Date();
  const safeBase = Number.isNaN(base.getTime()) ? new Date() : base;
  const utcMs = safeBase.getTime() + safeBase.getTimezoneOffset() * 60000;
  const ist = new Date(utcMs + 5.5 * 3600000);
  const year = ist.getFullYear();
  const month = String(ist.getMonth() + 1).padStart(2, '0');
  const day = String(ist.getDate()).padStart(2, '0');
  const hours = String(ist.getHours()).padStart(2, '0');
  const mins = String(ist.getMinutes()).padStart(2, '0');
  return {
    date: `${year}-${month}-${day}`,
    time: `${hours}:${mins}`,
    month: `${year}-${month}`,
  };
}
